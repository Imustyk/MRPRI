def test_aap_leave_one_supplier_out_drops_by_supplier():
    frame = pd.DataFrame(
        {
            "ocid": [f"o{i}" for i in range(12)],
            "y": [1, 1, 1, 1] + [0] * 8,
            "v0_max_score": [0.9, 0.55, 0.7, 0.35, 0.8, 0.6, 0.5, 0.45,
                             0.32, 0.28, 0.2, 0.1],
        }
    )
    matches = pd.DataFrame(
        {
            "ocid": ["o0", "o1", "o2", "o3"],
            "match_level": ["exact_normalised"] * 4,
            "blacklist_nrs": ["1", "1", "2", "2"],
        }
    )
    aap_metrics = {
        "per_entry": [
            {"blacklist_nr": 1, "match_level": "exact_normalised",
             "matched_key": "alpha"},
            {"blacklist_nr": 2, "match_level": "exact_normalised",
             "matched_key": "beta"},
        ]
    }
    table, summary = mod35.aap_leave_one_supplier_out(frame, matches, aap_metrics)
    assert summary["n_suppliers"] == 2
    assert summary["full_auc"] == pytest.approx(25 / 32)
    by_key = table.set_index("supplier_key")
    assert by_key.loc["alpha", "n_procedures_dropped"] == 2
    assert by_key.loc["alpha", "roc_auc_without"] == pytest.approx(11 / 16)
    assert by_key.loc["alpha", "delta_vs_full"] == pytest.approx(-0.09375)
    assert by_key.loc["beta", "roc_auc_without"] == pytest.approx(14 / 16)
    assert by_key.loc["beta", "n_positive_remaining"] == 2
    assert summary["auc_range"] == pytest.approx(0.1875)


