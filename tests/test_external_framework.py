_TINY_HEADER = (
    "ocid,tender_id,title,status,procurement_method,procurement_method_details,"
    "buyer_id,buyer_name,winner_id,winner_name,cpv_primary,"
    "published_date,tender_start,award_date,estimated_value,award_total,"
    "award_value,n_bidders,bid_window_days\n"
)


def _write_tiny(tmp_path: Path) -> tuple[Path, Path, Path]:
    """3 direct cluster rows + 9 direct controls + 4 open tenders (2024)."""
    lines = []
    cluster_money = (400, 700, 1000)
    for i, day in enumerate(("2024-01-01", "2024-02-01", "2024-03-15")):
        m = cluster_money[i]
        lines.append(
            f"ocid-{i},t{i},cluster {i},complete,OPEN,directaward,"
            f"B1,Buyer One,W1,Supplier One,45000000-9,"
            f"{day},{day},{day},{m},{m},{m},0,10"
        )
    pool_money = (100, 200, 300, 500, 600, 800, 900, 1100, 1200)
    for i in range(9):
        m = pool_money[i]
        day = f"2024-04-{i + 1:02d}"
        lines.append(
            f"ocid-{10 + i},t{10 + i},solo {i},complete,OPEN,directaward,"
            f"B{i + 2},Buyer {i + 2},W{i + 2},Supplier {i + 2},45000000-9,"
            f"{day},{day},{day},{m},{m},{m},0,15"
        )
    for i, nb in enumerate((1, 3, 0, 2)):
        day = f"2024-05-{i + 1:02d}"
        lines.append(
            f"ocid-{30 + i},t{30 + i},open {i},complete,OPEN,opentender,"
            f"B20,Buyer 20,W20,Supplier 20,30000000-2,"
            f"{day},{day},{day},{900 + i},{900 + i},{900 + i},{nb},{8 + i}"
        )
    features = tmp_path / "features.csv"
    features.write_text(_TINY_HEADER + "\n".join(lines) + "\n", encoding="utf-8")

    scores = tmp_path / "scores.csv"
    scores.write_text(
        "ocid,max_score,n_models_flagging\n"
        "ocid-0,0.50,1\n"
        "ocid-1,0.90,3\n"      # critical AND module-selected -> v0 group must skip it
        "ocid-2,0.40,1\n"
        + "".join(f"ocid-{10 + i},0.1{i},0\n" for i in range(9))
        + "ocid-30,0.80,3\n"
        "ocid-31,0.70,3\n"
        "ocid-32,0.20,1\n"
        "ocid-33,0.10,0\n",
        encoding="utf-8",
    )

    module = tmp_path / "module.csv"
    rows = ["ocid,n_module_hits,n_module_known,pair_prior_awards"]
    rows += ["ocid-0,1,2,0", "ocid-1,2,2,1", "ocid-2,2,2,2"]
    rows += [f"ocid-{10 + i},0,2,0" for i in range(9)]
    rows += [f"ocid-{30 + i},0,3,0" for i in range(4)]
    module.write_text("\n".join(rows) + "\n", encoding="utf-8")
    return features, scores, module


def test_script36_blinding_and_groups(tmp_path, monkeypatch):
    features, scores, module = _write_tiny(tmp_path)
    monkeypatch.setattr(mod36, "FEATURES_CSV", features)
    monkeypatch.setattr(mod36, "SCORES_CSV", scores)
    monkeypatch.setattr(mod36, "MODULE_CSV", module)
    outdir = tmp_path / "out"
    assert mod36.main(["--n", "2", "--outdir", str(outdir)]) == 0

    cases = pd.read_csv(outdir / "tables" / "expert_review_cases.csv")
    key = pd.read_csv(outdir / "tables" / "expert_review_key.csv")
    template = pd.read_csv(outdir / "tables" / "expert_review_template.csv")

    # reviewer-facing file: exactly the fact columns, nothing model-origin
    assert list(cases.columns) == ["case_id"] + mod36.BLINDED_COLUMNS
    for col in cases.columns:
        for bad in mod36.DISALLOWED_SUBSTRINGS:
            assert bad not in col.lower(), col

    # groups: sizes, disjointness, overlap exclusion, control matching
    sizes = key["group"].value_counts().to_dict()
    assert sizes == {"module_selected": 2, "v0_selected": 2, "matched_control": 2}
    assert key.groupby("ocid").size().max() == 1  # one group per case
    module_ocids = set(key.loc[key["group"] == "module_selected", "ocid"])
    assert module_ocids == {"ocid-1", "ocid-2"}  # hits 2, tie broken by pair awards
    v0_ocids = set(key.loc[key["group"] == "v0_selected", "ocid"])
    assert "ocid-1" not in v0_ocids  # critical overlap excluded from v0 group
    assert v0_ocids == {"ocid-30", "ocid-31"}
    control_ocids = set(key.loc[key["group"] == "matched_control", "ocid"])
    assert not control_ocids & (module_ocids | v0_ocids)

    # controls share the (group, year, quartile) stratum of module cases:
    # ocid-1 (700) and ocid-2 (1000) sit in direct quartiles 3 and 4 of 2024
    assert set(cases.loc[cases["ocid"].isin(control_ocids), "ocid"]) <= {
        "ocid-11", "ocid-12", "ocid-13", "ocid-14", "ocid-15",
        "ocid-16", "ocid-17", "ocid-18",
    }
    control_rows = cases.set_index("ocid").loc[list(control_ocids)]
    assert set(control_rows["procurement_method_details"]) == {"directaward"}

    # the answer form exists but is EMPTY - no manufactured assessments
    assert list(template.columns) == mod36.TEMPLATE_COLUMNS
    assert len(template) == 0

    payload = json.loads(
        (outdir / "methodology" / "expert_review_export.json").read_text(
            encoding="utf-8"
        )
    )
    assert payload["template_rows"] == 0
    assert payload["blinding"]["withheld_check"]["status"] == "pass"
    assert payload["status"].startswith("pending")
    assert "reviewable_case_precision" in payload["metric_definitions"]
    assert payload["groups"]["one_group_per_case"] is True


