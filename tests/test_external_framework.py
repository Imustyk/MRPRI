def test_cluster_bootstrap_paired_and_constant_score():
    rng = np.random.default_rng(0)
    n = 400
    y = np.array([1] * 40 + [0] * 360)
    perfect = y.astype(float) + rng.random(n) * 0.01
    noise = rng.random(n)
    const = np.ones(n)
    clusters = np.array([f"b{i % 40}" for i in range(n)])
    res = mod35.cluster_bootstrap_frame(
        y,
        {"v0_max_score": perfect, "noise": noise, "const": const},
        clusters,
        n_boot=60,
        seed=42,
    )
    assert res["rules"]["v0_max_score"]["roc_auc"]["point"] == pytest.approx(
        1.0, abs=0.02
    )
    assert res["rules"]["v0_max_score"]["roc_auc"]["ci"] is not None
    assert res["rules"]["v0_max_score"]["roc_auc"]["n_valid_boot"] == 60

    # constant score is flagged, not silently reported as 0.5
    assert "constant score" in res["rules"]["const"]["note"]
    assert res["rules"]["const"]["roc_auc"]["point"] == pytest.approx(0.5)

    pair = res["paired_vs_v0"]["noise"]["roc_auc"]
    assert pair["diff"] > 0
    assert pair["verdict"] == "ci_excludes_0"
    assert pair["ci"][0] > 0
    pr_pair = res["paired_vs_v0"]["noise"]["pr_auc"]
    assert pr_pair["verdict"] == "ci_excludes_0"


