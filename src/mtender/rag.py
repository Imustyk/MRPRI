"""RAG layer: normative corpus ingestion, BM25 retrieval, extractive answering.

Project requirements this module implements (section «Слой объяснения и
нормативная опора»):

* **Only official documents** — the source registry below records, for every
  act, the issuer, URL, edition and download date; hashes are computed on the
  raw files. No text is written from memory: everything quoted comes from the
  downloaded corpus.
* **Extractive answers** — an answer is assembled from retrieved corpus
  fragments verbatim. Nothing is generated by a model, so a hallucinated
  citation is structurally impossible; it is nevertheless re-verified at
  answer time (quote must be an exact substring of the stored chunk).
* **Explicit refusal** — if no fragment clears the relevance threshold, the
  answer refuses; there are no guesses.
* **Prompt-injection defence** — corpus and query text are untrusted *data*,
  never instructions: instruction-like lines are neutralised in place and the
  event is reported in the answer.
* **Formulation guard** — guilt / intent / offence-qualification wording is
  produced by neither the template nor the composer; a term guard verifies the
  template side of the answer.
* **Personal data** — only the normative corpus is quoted (it carries no
  personal data); procedure explanations quote MTender-published fields only.
* **Mandatory formulation** — every answer embeds the disclaimer
  «Индикатор потенциального риска, не доказательство нарушения или коррупции».
"""

