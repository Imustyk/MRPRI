def cluster_bootstrap_frame(
    y: np.ndarray,
    scores: dict[str, np.ndarray],
    clusters: np.ndarray,
    n_boot: int,
    seed: int,
) -> dict:
    """Cluster bootstrap (weights = drawn-cluster counts) for every ranking.

    Resampling whole clusters with replacement is equivalent to weighting
    every row of a drawn cluster; both ROC-AUC and PR-AUC accept row weights,
    so one weight vector per replicate scores *all* rankings on the *same*
    resample - which is exactly what a paired difference needs.
    """
    y = np.asarray(y, dtype=int)
    clusters = np.asarray(clusters).astype(str)
    rules = list(scores)
    uniq, inv = np.unique(clusters, return_inverse=True)
    n_clusters = len(uniq)
    rng = np.random.default_rng(seed)

    out: dict = {"n_rows": int(len(y)), "n_clusters": int(n_clusters),
                 "n_boot": n_boot, "rules": {}, "paired_vs_v0": {}}
    samples = {r: {"roc_auc": np.full(n_boot, np.nan),
                   "pr_auc": np.full(n_boot, np.nan)} for r in rules}
    has_both = np.unique(y).size >= 2
    for r in rules:
        point_roc = float(roc_auc_score(y, scores[r])) if has_both else float("nan")
        point_pr = (
            float(average_precision_score(y, scores[r])) if has_both else float("nan")
        )
        const = np.unique(scores[r]).size == 1
        out["rules"][r] = {
            "note": (
                "constant score - rule not applicable in this population; "
                "ROC-AUC 0.5 by definition"
                if const
                else ""
            ),
            "roc_auc": {"point": point_roc, "ci": None, "n_valid_boot": 0},
            "pr_auc": {"point": point_pr, "ci": None, "n_valid_boot": 0},
        }

    if has_both and n_boot > 0:
        for b in range(n_boot):
            drawn = np.bincount(
                rng.integers(0, n_clusters, size=n_clusters), minlength=n_clusters
            ).astype(np.float64)
            w = drawn[inv]
            # a replicate without one of the classes is undefined, not 0.5
            if w[y == 1].sum() <= 0 or w[y == 0].sum() <= 0:
                continue
            for r in rules:
                samples[r]["roc_auc"][b] = roc_auc_score(
                    y, scores[r], sample_weight=w
                )
                samples[r]["pr_auc"][b] = average_precision_score(
                    y, scores[r], sample_weight=w
                )
        for r in rules:
            for metric in ("roc_auc", "pr_auc"):
                vals = samples[r][metric]
                valid = vals[~np.isnan(vals)]
                entry = out["rules"][r][metric]
                entry["n_valid_boot"] = int(len(valid))
                if len(valid):
                    lo, hi = (float(x) for x in np.percentile(valid, [2.5, 97.5]))
                    entry["ci"] = [lo, hi]

        ref = "v0_max_score"
        for r in rules:
            if r == ref:
                continue
            pair: dict = {}
            for metric in ("roc_auc", "pr_auc"):
                diff = samples[ref][metric] - samples[r][metric]
                valid = diff[~np.isnan(diff)]
                point = (
                    out["rules"][ref][metric]["point"]
                    - out["rules"][r][metric]["point"]
                )
                if len(valid):
                    lo, hi = (float(x) for x in np.percentile(valid, [2.5, 97.5]))
                    pair[metric] = {
                        "diff": point,
                        "ci": [lo, hi],
                        "verdict": (
                            "ci_excludes_0" if (lo > 0 or hi < 0) else "ci_includes_0"
                        ),
                        "n_valid_boot": int(len(valid)),
                    }
                else:
                    pair[metric] = {"diff": point, "ci": None,
                                    "verdict": "insufficient_data",
                                    "n_valid_boot": 0}
            out["paired_vs_v0"][r] = pair
    return out


def budget_metrics(y: np.ndarray, score: np.ndarray) -> dict:
    """Point estimates for the auditor budgets (uncertainty reported for AUCs)."""
    y = np.asarray(y, dtype=int)
    out: dict = {}
    for k in K_VALUES:
        out[f"precision@{k}"] = float(precision_at_k(y, score, k))
        out[f"recall@{k}"] = float(recall_at_k(y, score, k))
        out[f"lift@{k}"] = float(lift_at_k(y, score, k))
    return out


def temporal_stability(
    y: np.ndarray, score: np.ndarray, years: np.ndarray, label: str, rule: str
) -> list[dict]:
    """ROC/PR AUC per pre-registered period; below the positive guard the row
    says why it is empty instead of printing a number."""
    rows: list[dict] = []
    y = np.asarray(y, dtype=int)
    score = np.asarray(score, dtype=float)
    periods = list(PERIODS) + [("all", 0, 9999)]
    for name, lo, hi in periods:
        mask = (years >= lo) & (years <= hi) if name != "all" else np.ones(len(y), bool)
        sub_y, sub_s = y[mask], score[mask]
        n_pos = int(sub_y.sum())
        row = {"label": label, "rule": rule, "period": name,
               "n_rows": int(len(sub_y)), "n_positives": n_pos,
               "roc_auc": None, "pr_auc": None, "note": ""}
        if n_pos < MIN_POSITIVES_TEMPORAL:
            row["note"] = (
                f"insufficient positives ({n_pos} < {MIN_POSITIVES_TEMPORAL})"
            )
        elif np.unique(sub_y).size < 2:
            row["note"] = "single class in period"
        else:
            row["roc_auc"] = float(roc_auc_score(sub_y, sub_s))
            row["pr_auc"] = float(average_precision_score(sub_y, sub_s))
        rows.append(row)
    return rows


def aap_leave_one_supplier_out(
    frame: pd.DataFrame, matches: pd.DataFrame, aap_metrics: dict
) -> tuple[pd.DataFrame, dict]:
    """Drop each interdicted supplier's procedures and recompute the v0 AUC.

    ``blacklist_nrs`` in the matches table links a positive procedure to the
    blacklist entries (and hence to the normalised supplier key) it matched,
    so the sensitivity is computed per *supplier*, not per display-name
    variant.
    """
    nr_to_key: dict[int, str] = {}
    for entry in aap_metrics.get("per_entry", []):
        if entry.get("match_level") == "exact_normalised" and entry.get("blacklist_nr"):
            nr_to_key[int(entry["blacklist_nr"])] = entry.get("matched_key") or ""

    def supplier_of(nr_cell) -> str:
        nrs = [int(n) for n in re.findall(r"\d+", str(nr_cell))]
        keys = sorted({nr_to_key[n] for n in nrs if n in nr_to_key})
        return "+".join(keys) if keys else "unmapped"

    m = matches[matches["match_level"] == "exact_normalised"].copy()
    m["supplier_key"] = m["blacklist_nrs"].map(supplier_of)
    full_auc = float(
        roc_auc_score(frame["y"].to_numpy(int), frame["v0_max_score"].to_numpy(float))
    )
    rows = []
    for key, grp in m.groupby("supplier_key"):
        keep = ~frame["ocid"].isin(set(grp["ocid"]))
        sub = frame[keep]
        auc = float(roc_auc_score(sub["y"].to_numpy(int), sub["v0_max_score"].to_numpy(float)))
        rows.append({
            "supplier_key": key,
            "n_procedures_dropped": int(len(grp)),
            "n_positive_remaining": int(sub["y"].sum()),
            "roc_auc_without": auc,
            "delta_vs_full": auc - full_auc,
        })
    table = pd.DataFrame(rows).sort_values(
        "delta_vs_full", key=lambda s: s.abs(), ascending=False
    ).reset_index(drop=True)
    summary = {
        "full_auc": full_auc,
        "n_suppliers": int(len(table)),
        "auc_min": float(table["roc_auc_without"].min()) if len(table) else None,
        "auc_max": float(table["roc_auc_without"].max()) if len(table) else None,
        "auc_range": (
            float(table["roc_auc_without"].max() - table["roc_auc_without"].min())
            if len(table)
            else None
        ),
        "max_abs_delta": (
            float(table["delta_vs_full"].abs().max()) if len(table) else None
        ),
        "most_influential_supplier": (
            table.iloc[0]["supplier_key"] if len(table) else None
        ),
        "note": "a wide range would mean the headline number is driven by a "
        "single supplier; the range is reported, never hidden",
    }
    return table, summary


def _read_json(path: Path) -> dict | None:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


