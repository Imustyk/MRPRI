#!/usr/bin/env python3
"""Step 35 - structured external validation framework (Phase 5, 2026-10-20).

MEASUREMENT ONLY. Production v0 scores are *read*, never recomputed; no
threshold is tuned; no score direction is flipped after seeing an AUC; no
missing label source is invented (blocked sources appear in the registry with
their blocker text). The AAP/ANSC labels are weak proxies, never confirmed
corruption ground truth.

What this script adds on top of the existing scripts 09/12/31:

1. **One provenance registry** for every label source with the full schema the
   brief requires - source, entity type, event date, publication date,
   matching method, confidence/matching status, known limitations - plus an
   explicit ``status`` (available / blocked / pending) and blocker text for
   the sources that are *not* available (ANSC decisions, court rulings
   HG 957/2017 and HG 1420/2016, Metodologia AAP, MoF cross-check emptiness,
   expert review pending).
2. **Complaints vs decisions distinction**: the ANSC inventory's document
   types are checked at runtime; no decision documents exist in the corpus,
   so the label stays "a complaint document exists" - filing, not outcome -
   and the missing decision source is recorded as a blocker, never silently
   conflated.
3. **AAP leave-one-supplier-out sensitivity**: the headline AUC is recomputed
   with each interdicted supplier's procedures removed, so the influence of
   any single supplier is visible.
4. **Paired cluster-bootstrap differences of v0 against simple baselines**
   (amount, fewer-bidders, value-within-CPV, single-bidder rule, ensemble
   votes, random ranking) - same resamples for both rankings, CIs on ROC-AUC
   and PR-AUC, verdict "CI excludes/includes 0". Directions are pre-registered
   in ``BASELINE_SPECS`` and never flipped.
5. **Temporal stability** of every ranking per period (2018-2021 / 2022-2024),
   with a minimum-positive guard instead of a fabricated number.

The experimental module ranking (``scripts/34`` ``n_module_hits``) is included
as a rule when ``risk_module_indicators.csv`` is present, so Phase 7's
"experimental vs baselines" comparison comes out of the same run.

Eligibility: evaluation happens only within populations where the label is
determinable (AAP: procedures with a named winning supplier; ANSC: competitive
procedures ``n_bidders >= 2``, matching MTA-0013). Labels are evaluation
targets only - they never become model inputs, and AAP decisions that postdate
the procedure are stated as such (no future-event leakage into scoring).

Outputs (results/ is gitignored, regenerated by this script):

* ``results/methodology/external_label_registry.json``
* ``results/methodology/external_validation_framework.json``
* ``results/tables/external_baselines.csv``
* ``results/tables/aap_leave_one_supplier_out.csv``
* ``results/tables/temporal_stability_external.csv``

Usage::

    .venv/bin/python scripts/35_external_validation.py [--boot 1000] [--seed 42]
"""

