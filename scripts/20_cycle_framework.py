    def beats_no_flag(ext: dict) -> bool:
        """Rule = ``votes >= 3`` at c_miss=200 costs less than flagging nothing.

        cost = c_miss * FN + FP with FP = flagged - TP, FN = positives - TP,
        TP = consensus_precision * flagged; no-flag cost = c_miss * positives.
        """
        c_miss = STOP_CRITERIA["c_miss_for_economics"]
        flagged = ext["consensus_n"] or 0
        precision = ext["consensus_precision"] or 0.0
        tp = precision * flagged
        return bool(ext["positives"] and flagged
                    and c_miss * (ext["positives"] - tp) + (flagged - tp)
                    < c_miss * ext["positives"])

