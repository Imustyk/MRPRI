"""Step 20 - iterative-cycle framework: one variant, the whole metric suite.

The addendum to the brief replaces the linear pipeline with an iterative cycle:
every cycle changes **exactly one thing**, re-measures the *same* metric suite,
writes ``reports/cycle_N.md`` and journals the change in ``cycle_log.md``.
This script is the measuring instrument those cycles share.

A *variant* is a declarative change on top of the production configuration
(22 features, MAD z>5 / IF(300, 0.05, 42) / LOF(k=20) / OCSVM(nu=0.05),
bands = votes, ranking = max of percentile ranks):

    v0_baseline          production configuration, re-measured apples-to-apples
    v1_merge_duplicate   drop ``winner_share_of_buyer_awards`` (byte-identical
                         duplicate of ``buyer_supplier_repeat_share``)
    v2_mean_rank         rank combination max-percentile -> mean-percentile
                         (bands unchanged; only the within-band ordering changes)
    v3_drop_behavioural  drop the four behavioural features
    v4_datafix           the author-requested data-artifact fixes, measured as
                         one variant: merge phantom supplier identities
                         (whitespace/case in ``winner_id``) and recompute the
                         behavioural features, explicit winsorisation caps on
                         the two uncapped value features, cleanup of the
                         literal ``buyer_locality`` placeholder string, and the
                         v1 duplicate drop (see ``apply_datafix``)
    v4b_datafix_keep_duplicate
                         the same data-artifact fixes WITHOUT the duplicate
                         drop, so the two effects are separable: v4b vs v0 =
                         the data fixes alone; v4 vs v4b = the duplicate drop
                         under the fixed data

For every variant the suite measures, with the SAME protocol each time:

  1. external metrics vs the AAP label, split into tuning (2018-2021) and
     holdout (2022-2024): ROC-AUC / PR-AUC / precision@k with bootstrap CIs,
     consensus-rule precision with Wilson CI
  2. paired-bootstrap delta of ROC-AUC against v0 on the TUNING split only
     (the decision metric; holdout is reported but never decides)
  3. band calibration (band shares, consensus load per year)
  4. detector agreement (pairwise Cohen's kappa)
  5. top-N stability across seeds: Jaccard of top-200 and of the consensus set,
     coefficient of variation of the consensus count
  6. hyperparameter sensitivity: contamination / n_neighbors / nu varied one at
     a time around the production values
  7. drift between the tuning and holdout score distributions (KS, PSI)

Stop criteria are evaluated against explicitly proposed thresholds (see
``STOP_CRITERIA``); they are proposals for the author, not hidden defaults.
C6 reads the section-E bias audit (``results/methodology/bias_audit.json``):
any "нарушение"/"предупреждение" verdict fails it - corpus-level on the
production bands, re-audited when a new band configuration is proposed
(see ``evaluate_c6_bias_audit``).

Usage (cycle 1: v0 then v1, etc.):
    .venv/bin/python scripts/20_cycle_framework.py --variants v0 v1 v2 v3
"""

